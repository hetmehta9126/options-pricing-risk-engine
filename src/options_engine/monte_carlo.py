"""
Monte Carlo pricer for European options under geometric Brownian motion.

We simulate terminal stock prices directly (no need to simulate the full
path for a European option, since the payoff only depends on S_T), then
average the discounted payoff. Because this is a random estimate, we
also report the standard error so we know how precise the estimate is.

All simulated paths and prices are synthetic, generated by this code
with a fixed random seed for reproducibility. They are not market data.
"""

from dataclasses import dataclass

import numpy as np

from .black_scholes import BSInputs


@dataclass
class MCResult:
    """Monte Carlo price estimate with its standard error."""

    price: float
    std_error: float
    num_paths: int


def simulate_terminal_prices(inputs: BSInputs, num_paths: int, rng: np.random.Generator) -> np.ndarray:
    """
    Draw num_paths terminal stock prices under risk-neutral GBM:

        S_T = S0 * exp((r - q - 0.5*sigma^2) * T + sigma * sqrt(T) * Z)

    with Z standard normal.
    """
    S, T, r, sigma, q = inputs.spot, inputs.maturity, inputs.rate, inputs.volatility, inputs.dividend_yield
    z = rng.standard_normal(num_paths)
    drift = (r - q - 0.5 * sigma**2) * T
    diffusion = sigma * np.sqrt(T) * z
    return S * np.exp(drift + diffusion)


def mc_price(
    inputs: BSInputs,
    option_type: str,
    num_paths: int,
    seed: int,
) -> MCResult:
    """Estimate a European option price by Monte Carlo simulation."""
    rng = np.random.default_rng(seed)
    terminal_prices = simulate_terminal_prices(inputs, num_paths, rng)

    if option_type.lower() == "call":
        payoffs = np.maximum(terminal_prices - inputs.strike, 0.0)
    elif option_type.lower() == "put":
        payoffs = np.maximum(inputs.strike - terminal_prices, 0.0)
    else:
        raise ValueError(f"option_type must be 'call' or 'put', got {option_type!r}")

    discount = np.exp(-inputs.rate * inputs.maturity)
    discounted_payoffs = discount * payoffs

    estimate = float(np.mean(discounted_payoffs))
    # Standard error of the mean: sample std / sqrt(n).
    std_error = float(np.std(discounted_payoffs, ddof=1) / np.sqrt(num_paths))

    return MCResult(price=estimate, std_error=std_error, num_paths=num_paths)
