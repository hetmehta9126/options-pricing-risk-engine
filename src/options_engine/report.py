"""
Builds a Markdown summary report from the numbers produced by main.py.

This module does not compute anything itself -- it only formats numbers
that were already calculated elsewhere, so the report can never show a
number that didn't actually come out of a run of the pipeline.
"""

import os
from datetime import datetime


def build_report(results: dict, output_dir: str) -> str:
    """
    Write outputs/report.md from a results dictionary produced by
    main.py. See main.py for the exact keys expected.
    """
    lines = []
    lines.append("# Options Pricing and Risk Engine -- Run Report")
    lines.append("")
    lines.append(f"Generated: {datetime.now().isoformat(timespec='seconds')}")
    lines.append("")
    lines.append(
        "All numbers below come from simulated or synthetic data generated by "
        "this run of `main.py`. Nothing here is real market data, and nothing "
        "here is a claim about trading performance."
    )
    lines.append("")

    # --- Base scenario ---
    base = results["base_scenario"]
    lines.append("## 1. Base pricing scenario")
    lines.append("")
    lines.append(
        f"Spot = {base['spot']}, Strike = {base['strike']}, Maturity = {base['maturity']} yr, "
        f"Rate = {base['rate']:.4%}, Volatility = {base['volatility']:.2%}, "
        f"Dividend yield = {base['dividend_yield']:.2%}"
    )
    lines.append("")
    lines.append("| Quantity | Call | Put |")
    lines.append("|---|---|---|")
    lines.append(f"| Black-Scholes price | {base['call_price']:.4f} | {base['put_price']:.4f} |")
    lines.append(f"| Delta | {base['call_greeks']['delta']:.4f} | {base['put_greeks']['delta']:.4f} |")
    lines.append(f"| Gamma | {base['call_greeks']['gamma']:.4f} | {base['put_greeks']['gamma']:.4f} |")
    lines.append(f"| Vega (per vol pt) | {base['call_greeks']['vega']:.4f} | {base['put_greeks']['vega']:.4f} |")
    lines.append(f"| Theta (per day) | {base['call_greeks']['theta']:.4f} | {base['put_greeks']['theta']:.4f} |")
    lines.append(f"| Rho (per 1% rate) | {base['call_greeks']['rho']:.4f} | {base['put_greeks']['rho']:.4f} |")
    lines.append("")
    lines.append(f"Put-call parity check (call - put - forward value): {base['parity_diff']:.2e}")
    lines.append("")

    # --- Implied volatility ---
    iv = results["implied_vol_check"]
    lines.append("## 2. Implied volatility solver check")
    lines.append("")
    lines.append(
        f"Priced a call with volatility {iv['input_vol']:.2%}, then solved for implied "
        f"volatility from that price."
    )
    lines.append("")
    lines.append(
        f"Recovered volatility: {iv['recovered_vol']:.6f} "
        f"(method: {iv['method']}, iterations: {iv['iterations']}, "
        f"absolute error vs input: {abs(iv['recovered_vol'] - iv['input_vol']):.2e})"
    )
    lines.append("")

    # --- Binomial convergence ---
    binom = results["binomial_convergence"]
    lines.append("## 3. CRR binomial convergence to Black-Scholes")
    lines.append("")
    lines.append("| Steps | Binomial price | Abs. error vs BS |")
    lines.append("|---|---|---|")
    for steps, bprice, err in zip(binom["steps"], binom["prices"], binom["abs_errors"]):
        lines.append(f"| {steps} | {bprice:.6f} | {err:.2e} |")
    lines.append("")

    # --- Monte Carlo convergence ---
    mc = results["mc_convergence"]
    lines.append("## 4. Monte Carlo convergence to Black-Scholes")
    lines.append("")
    lines.append("| Paths | MC price | Std. error | Abs. error vs BS |")
    lines.append("|---|---|---|---|")
    for n, mprice, se, err in zip(mc["paths"], mc["prices"], mc["std_errors"], mc["abs_errors"]):
        lines.append(f"| {n} | {mprice:.6f} | {se:.6f} | {err:.2e} |")
    lines.append("")

    # --- IV smile ---
    smile = results["iv_smile"]
    lines.append("## 5. Implied volatility smile (synthetic skew)")
    lines.append("")
    lines.append(
        "Prices were generated from a synthetic skew model (see `config.py`), "
        "then the IV solver was run on each price to recover the smile."
    )
    lines.append("")
    lines.append(f"Max absolute error between input and recovered vol: {smile['max_abs_error']:.2e}")
    lines.append("")

    # --- Hedging simulation ---
    hedge = results["hedging_summary"]
    lines.append("## 6. Delta-hedging simulation")
    lines.append("")
    lines.append(
        f"{hedge['num_paths']} simulated paths per setting, {hedge['num_steps']} steps "
        f"over {hedge['maturity']} year(s), random seed = {hedge['seed']}."
    )
    lines.append("")
    lines.append("| Rebalancing | Cost rate | Mean P&L | Std dev P&L |")
    lines.append("|---|---|---|---|")
    for row in hedge["rows"]:
        lines.append(
            f"| {row['frequency']} | {row['cost_rate']:.2%} | {row['mean_pnl']:.4f} | {row['std_pnl']:.4f} |"
        )
    lines.append("")
    lines.append(
        "As expected, the standard deviation of hedging P&L shrinks as rebalancing "
        "gets more frequent (less discretization error) and grows as transaction "
        "costs or rebalancing frequency increase (more cost drag)."
    )
    lines.append("")

    # --- Chart index ---
    lines.append("## 7. Charts")
    lines.append("")
    for name, path in results["chart_paths"].items():
        lines.append(f"- {name}: `{os.path.basename(path)}`")
    lines.append("")

    report_text = "\n".join(lines)
    os.makedirs(output_dir, exist_ok=True)
    report_path = os.path.join(output_dir, "report.md")
    with open(report_path, "w") as f:
        f.write(report_text)

    return report_path
